// Rebuild the bundled geometry from the supplied Tinkercad export. No asset upload required.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const root = path.resolve(__dirname, "..");
const sourceRoot = path.join(root, "assets/models/fish-freezer");
const obj = fs.readFileSync(path.join(sourceRoot, "tinker.obj"), "utf8");
const mtl = fs.readFileSync(path.join(sourceRoot, "obj.mtl"), "utf8");
const materials = {};
let material;
for (const line of mtl.split(/\r?\n/)) {
  const [kind, ...values] = line.trim().split(/\s+/);
  if (kind === "newmtl") material = values[0];
  if (kind === "Kd") materials[material] = values.map(Number);
  if (kind === "d" && Number(values[0]) !== 1) throw new Error("Handle source transparency explicitly");
}
const vertices = [], objects = [];
let object;
for (const line of obj.split(/\r?\n/)) {
  const [kind, ...values] = line.trim().split(/\s+/);
  if (kind === "o") {
    object = { name: values[0], faces: [] };
    objects.push(object);
  } else if (kind === "v") vertices.push(values.map(Number));
  else if (kind === "usemtl") object.color = materials[values[0]];
  else if (kind === "f") {
    if (values.length !== 3) throw new Error("Expected triangulated OBJ faces");
    const face = values.map(value => Number(value.split("/")[0]));
    if (face.some(index => index < 1 || index > vertices.length)) throw new Error("Invalid face index");
    object.faces.push(face);
  }
}
if (vertices.length !== 166 || objects.length !== 11 || objects.reduce((n, o) => n + o.faces.length, 0) !== 288)
  throw new Error("Unexpected freezer source; review the new export before importing");
const subtract = (a, b) => a.map((v, i) => v - b[i]);
const dot = (a, b) => a.reduce((sum, v, i) => sum + v * b[i], 0);
const magnitude = a => Math.sqrt(dot(a, a));
// Collapse complete cuboids to one solid Part, retaining their original rotation.
// The curved cover, cavity and sloping insert keep every source triangle.
for (const object of objects) {
  if (!object.color) throw new Error("Missing source color");
  const indices = [...new Set(object.faces.flat())];
  if (indices.length !== 8 || object.faces.length !== 12) continue;
  const points = indices.map(i => vertices[i - 1]);
  const origin = points[0];
  const edges = points.slice(1).map(p => subtract(p, origin));
  outer: for (let i = 0; i < edges.length; i++) for (let j = i + 1; j < edges.length; j++) for (let k = j + 1; k < edges.length; k++) {
    const axes = [edges[i], edges[j], edges[k]];
    const sizes = axes.map(magnitude);
    const units = axes.map((a, index) => a.map(v => v / sizes[index]));
    if (Math.abs(dot(units[0], units[1])) > 0.00001 || Math.abs(dot(units[1], units[2])) > 0.00001 || Math.abs(dot(units[0], units[2])) > 0.00001) continue;
    for (let mask = 0; mask < 8; mask++) {
      const corner = origin.map((v, axis) => v + axes.reduce((n, edge, e) => n + ((mask >> e) & 1) * edge[axis], 0));
      if (!points.some(point => magnitude(subtract(point, corner)) < 0.001)) continue outer;
    }
    // Store the source basis. The runtime rebuilds an orthonormal right-handed frame.
    object.box = { center: origin.map((v, axis) => v + axes.reduce((n, a) => n + a[axis] / 2, 0)), size: sizes, right: units[0], up: units[1] };
    break outer;
  }
}
const hash = crypto.createHash("sha256").update(obj).update(mtl).digest("hex");
const vector = v => `Vector3.new(${v.map(n => Number(n.toFixed(9))).join(", ")})`;
const rows = [
  "-- Generated by node scripts/import-fish-freezer.cjs; edit the source OBJ/MTL instead.",
  `-- Source: Smashing Elzing-Habbi.zip; SHA-256 (OBJ + MTL): ${hash}`,
  "-- Original Tinkercad coordinates; Z is up. Every source object and face is retained.",
  "return {", `\tboundsMin = ${vector([0,1,2].map(a=>Math.min(...vertices.map(v=>v[a]))))},`, `\tboundsMax = ${vector([0,1,2].map(a=>Math.max(...vertices.map(v=>v[a]))))},`, `\tsourceHash = "${hash}",`, "\tvertices = {",
  ...vertices.map(v => `\t\t${vector(v)},`), "\t},", "\tobjects = {",
];
for (const object of objects) {
  rows.push("\t\t{", `\t\t\tname = "${object.name}",`, `\t\t\tcolor = Color3.new(${object.color.join(", ")}),`);
  if (object.box) {
    rows.push("\t\t\tbox = {");
    for (const [key, value] of Object.entries(object.box)) rows.push(`\t\t\t\t${key} = ${vector(value)},`);
    rows.push("\t\t\t},");
  }
  rows.push("\t\t\tfaces = {");
  for (const face of object.faces) rows.push(`\t\t\t\t{ ${face.join(", ")} },`);
  rows.push("\t\t\t},", "\t\t},");
}
rows.push("\t},", "}", "");
const target = path.join(root, "src/server/Map/FishFreezerGeometry.luau");
const output = rows.join("\n");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== output) throw new Error("Bundled freezer geometry differs from source; rerun importer");
} else fs.writeFileSync(target, output);
console.log(`Freezer: ${vertices.length} vertices, ${objects.length} objects, 288 source faces, ${objects.filter(o => o.box).length} solid cuboids; source ${hash}`);
